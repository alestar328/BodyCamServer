def main():

    # -------------------------------------------------------------------------
    # COMMAND-LINE ARGUMENT VALIDATION
    # -------------------------------------------------------------------------

    # Expected:
    #
    #   argv[0] script
    #   argv[1] input file
    #   argv[2] key file
    #   argv[3] output file
    #
    # Therefore len(sys.argv) must equal 4.
    #
    if len(sys.argv) != 4:

        print()
        print("=" * 70)
        print("AES-256-GCM ENCRYPTION + SHA-256 BENCHMARK")
        print("ANDROID / TERMUX")
        print("=" * 70)

        print()
        print("Usage:")
        print()

        print(
            "  python aes_gcm_benchmark.py "
            "<input_file> <key_file> <output_file>"
        )

        print()
        print("Example:")
        print()

        print(
            "  python aes_gcm_benchmark.py "
            "~/storage/downloads/video.mp4 "
            "~/storage/downloads/aes.key "
            "~/storage/downloads/video.mp4.enc"
        )

        print()
        print("Required Python package:")
        print()
        print("  pip install cryptography")

        print()
        print("Termux shared-storage setup:")
        print()
        print("  termux-setup-storage")

        print()

        sys.exit(1)


    # -------------------------------------------------------------------------
    # GET COMMAND-LINE PARAMETERS
    # -------------------------------------------------------------------------

    input_file = sys.argv[1]
    key_file = sys.argv[2]
    output_file = sys.argv[3]


    # -------------------------------------------------------------------------
    # VERIFY INPUT FILE
    # -------------------------------------------------------------------------

    if not os.path.isfile(input_file):

        print()
        print(f"ERROR: Input file not found:")
        print(f"       {input_file}")
        print()

        sys.exit(1)


    # -------------------------------------------------------------------------
    # VERIFY KEY FILE
    # -------------------------------------------------------------------------

    if not os.path.isfile(key_file):

        print()
        print(f"ERROR: AES key file not found:")
        print(f"       {key_file}")
        print()

        sys.exit(1)


    # -------------------------------------------------------------------------
    # PREVENT ACCIDENTAL INPUT DESTRUCTION
    # -------------------------------------------------------------------------

    # If input_file and output_file point to the same path, opening the output
    # file for writing would truncate the original file.
    #
    # Therefore this condition is explicitly prohibited.
    #
    if os.path.abspath(input_file) == os.path.abspath(output_file):

        print()
        print("ERROR: Input and output files cannot be the same.")
        print()
        print("This protection prevents accidental destruction of")
        print("the original input file.")
        print()

        sys.exit(1)


    # -------------------------------------------------------------------------
    # LOAD AES KEY
    # -------------------------------------------------------------------------

    key = load_key(key_file)


    # -------------------------------------------------------------------------
    # DETERMINE INPUT FILE SIZE
    # -------------------------------------------------------------------------

    file_size = os.path.getsize(input_file)

    # MB value used for throughput calculation.
    #
    # Technically this is MiB because we divide by 1024 × 1024.
    #
    # It is labelled MB here for convenient benchmark reporting.
    file_size_mb = file_size / (1024 * 1024)


    # -------------------------------------------------------------------------
    # DISPLAY TEST INFORMATION
    # -------------------------------------------------------------------------

    print()
    print("=" * 70)
    print("AES-256-GCM + SHA-256 ANDROID BENCHMARK")
    print("=" * 70)

    print()
    print("TEST CONFIGURATION")
    print("-" * 70)

    print(f"Input file      : {input_file}")
    print(f"Input size      : {format_size(file_size)}")
    print(f"Input bytes     : {file_size:,}")
    print(f"Key file        : {key_file}")
    print(f"Output file     : {output_file}")

    print()
    print("CRYPTOGRAPHIC CONFIGURATION")
    print("-" * 70)

    print("AES algorithm   : AES-256")
    print("AES mode        : GCM")
    print("AES key size    : 256 bits / 32 bytes")
    print("GCM nonce size  : 96 bits / 12 bytes")
    print("GCM tag size    : 128 bits / 16 bytes")
    print("Hash algorithm  : SHA-256")

    print()
    print("I/O CONFIGURATION")
    print("-" * 70)

    print(
        f"Chunk size      : "
        f"{CHUNK_SIZE // (1024 * 1024)} MB"
    )

    print()
    print("IMPORTANT BENCHMARK NOTE")
    print("-" * 70)

    print(
        "Reported times include Android storage I/O."
    )

    print(
        "Therefore these results represent practical end-to-end"
    )

    print(
        "file-processing performance, not pure AES/SHA CPU performance."
    )


    # -------------------------------------------------------------------------
    # START TOTAL BENCHMARK TIMER
    # -------------------------------------------------------------------------

    total_start = time.perf_counter()


    # =========================================================================
    # TEST 1: SHA-256
    # =========================================================================

    print()
    print("=" * 70)
    print("[1/2] SHA-256 HASH BENCHMARK")
    print("=" * 70)

    sha256_digest, hash_time = calculate_sha256(input_file)


    # Calculate SHA throughput.
    #
    # Example:
    #
    #   1000 MB file / 2 seconds
    #
    #       = 500 MB/s
    #
    if hash_time > 0:
        hash_speed = file_size_mb / hash_time
    else:
        hash_speed = 0

    print()
    print("      SHA-256 operation complete.")


    # =========================================================================
    # TEST 2: AES-256-GCM
    # =========================================================================

    print()
    print("=" * 70)
    print("[2/2] AES-256-GCM ENCRYPTION BENCHMARK")
    print("=" * 70)

    nonce, tag, encryption_time = encrypt_aes256_gcm(
        input_file,
        output_file,
        key
    )


    # Calculate AES encryption throughput.
    if encryption_time > 0:
        encryption_speed = file_size_mb / encryption_time
    else:
        encryption_speed = 0

    print()
    print("      AES-256-GCM operation complete.")


    # -------------------------------------------------------------------------
    # STOP TOTAL BENCHMARK TIMER
    # -------------------------------------------------------------------------

    total_time = time.perf_counter() - total_start


    # -------------------------------------------------------------------------
    # GET FINAL ENCRYPTED FILE SIZE
    # -------------------------------------------------------------------------

    output_size = os.path.getsize(output_file)


    # =========================================================================
    # FINAL RESULTS
    # =========================================================================

    print()
    print("=" * 70)
    print("FINAL BENCHMARK RESULTS")
    print("=" * 70)


    # -------------------------------------------------------------------------
    # CRYPTOGRAPHIC INFORMATION
    # -------------------------------------------------------------------------

    print()
    print("CRYPTOGRAPHIC INFORMATION")
    print("-" * 70)

    print(f"Encryption      : AES-256-GCM")
    print(f"Key size        : 256 bits")
    print(f"Nonce size      : {NONCE_SIZE * 8} bits")
    print(f"Tag size        : {TAG_SIZE * 8} bits")

    # Nonce is not secret and may safely be reported.
    print(f"Nonce           : {nonce.hex()}")

    # Authentication tag is also not secret.
    print(f"GCM tag         : {tag.hex()}")


    # -------------------------------------------------------------------------
    # SHA-256 RESULTS
    # -------------------------------------------------------------------------

    print()
    print("SHA-256 RESULTS")
    print("-" * 70)

    print(f"SHA-256         : {sha256_digest}")
    print(f"Hash time       : {hash_time:.6f} seconds")
    print(f"Hash throughput : {hash_speed:.2f} MB/s")


    # -------------------------------------------------------------------------
    # AES RESULTS
    # -------------------------------------------------------------------------

    print()
    print("AES-256-GCM RESULTS")
    print("-" * 70)

    print(f"Encryption time : {encryption_time:.6f} seconds")
    print(f"AES throughput  : {encryption_speed:.2f} MB/s")


    # -------------------------------------------------------------------------
    # FILE INFORMATION
    # -------------------------------------------------------------------------

    print()
    print("FILE INFORMATION")
    print("-" * 70)

    print(f"Original size   : {format_size(file_size)}")
    print(f"Original bytes  : {file_size:,}")

    print(f"Encrypted size  : {format_size(output_size)}")
    print(f"Encrypted bytes : {output_size:,}")

    print(
        f"File overhead   : "
        f"{output_size - file_size:,} bytes"
    )


    # -------------------------------------------------------------------------
    # TIMING SUMMARY
    # -------------------------------------------------------------------------

    print()
    print("TIMING SUMMARY")
    print("-" * 70)

    print(
        f"SHA-256 time    : {hash_time:.6f} seconds"
    )

    print(
        f"AES-GCM time    : {encryption_time:.6f} seconds"
    )

    print(
        f"Combined crypto : "
        f"{hash_time + encryption_time:.6f} seconds"
    )

    print(
        f"Total runtime   : {total_time:.6f} seconds"
    )


    # -------------------------------------------------------------------------
