import os

# os provides operating-system functionality.
#
# We use it for:
#
#   - os.path.isfile()
#   - os.path.abspath()
#   - os.path.getsize()
#   - os.urandom()
#
# Of particular importance:
#
#   os.urandom()
#
# provides cryptographically secure random bytes obtained from the operating
# system. We use this to generate the AES-GCM nonce.


import sys

# sys provides access to command-line arguments.
#
# For example:
#
#   python aes_gcm_benchmark.py video.mp4 aes.key video.enc
#
# becomes:
#
#   sys.argv[0] = aes_gcm_benchmark.py
#   sys.argv[1] = video.mp4
#   sys.argv[2] = aes.key
#   sys.argv[3] = video.enc


import time

# time is used for benchmark timing.
#
# We use:
#
#   time.perf_counter()
#
# rather than wall-clock time.
#
# perf_counter() provides a high-resolution monotonic performance counter
# suitable for measuring elapsed execution time.


import hashlib

# hashlib provides Python's standard cryptographic hashing functions.
#
# We specifically use:
#
#   hashlib.sha256()
#
# to calculate the SHA-256 digest of the original input file.


# =============================================================================
# IMPORT CRYPTOGRAPHY LIBRARY
# =============================================================================

from cryptography.hazmat.primitives.ciphers import (
    Cipher,
    algorithms,
    modes
)

# Cipher
# ------
#
# Provides the cryptographic cipher interface.
#
#
# algorithms.AES
# --------------
#
# Selects the AES block cipher.
#
# Because our supplied key is 32 bytes / 256 bits, the cryptography library
# will use AES-256.
#
#
# modes.GCM
# ---------
#
# Selects Galois/Counter Mode.
#
# GCM provides both:
#
#   CONFIDENTIALITY
#
#       The file contents are encrypted.
#
#   AUTHENTICATION / INTEGRITY
#
#       Modification of ciphertext can be detected using the authentication
#       tag.
#
# This combination is known as:
#
#       AEAD
#
#       Authenticated Encryption with Associated Data.


# =============================================================================
# CONFIGURATION CONSTANTS
# =============================================================================


CHUNK_SIZE = 4 * 1024 * 1024

# File processing chunk size.
#
# 4 × 1024 × 1024 bytes
#
# = 4,194,304 bytes
# = 4 MiB
#
# Instead of loading an entire multi-GB MP4 into memory, we repeatedly read
# 4 MB blocks.
#
# Conceptually:
#
#       FILE
#        |
#        v
#    +--------+
#    | 4 MB   |
#    +--------+
#        |
#        v
#     process
#        |
#        v
#    +--------+
#    | 4 MB   |
#    +--------+
#        |
#       ...
#
# This keeps memory consumption approximately constant regardless of whether
# the input file is:
#
#       100 MB
#       1 GB
#       10 GB
#       50 GB
#
# Android note:
#
# Chunk size can influence benchmark results because storage I/O, Python
# overhead and filesystem caching all contribute to observed performance.


NONCE_SIZE = 12

# AES-GCM nonce size.
#
# 12 bytes
#
# = 96 bits
#
# 96 bits is the conventional/recommended nonce length for GCM.
#
# A NEW RANDOM NONCE MUST BE GENERATED FOR EACH ENCRYPTION OPERATION.


TAG_SIZE = 16

# GCM authentication tag size.
#
# 16 bytes
#
# = 128 bits
#
# The authentication tag allows a decryptor to verify that the ciphertext
# has not been modified.
#
# NOTE:
#
# TAG_SIZE is documented here primarily for understanding the output format.
# The cryptography library produces the GCM tag from encryptor.tag.


KEY_SIZE = 32

# AES key size.
#
# 32 bytes
#
# 32 × 8 = 256 bits
#
# Therefore:
#
#       AES-256


MAGIC = b"AES256GCM01"

# Simple file-format identifier.
#
# This is NOT a cryptographic value.
#
# It simply provides a recognizable header indicating that the encrypted
# file was produced using this utility.
#
# Current value:
#
#       AES256GCM01
#
# Length:
#
#       11 bytes


# =============================================================================
# HUMAN-READABLE FILE SIZE FUNCTION
# =============================================================================

def format_size(num_bytes):
    """
    Convert a byte count into a human-readable representation.

    Example:

        1024        -> 1.00 KB
        1048576     -> 1.00 MB
        1073741824  -> 1.00 GB

    This function is used only for reporting.

    It has no effect on encryption or hashing.
    """

    units = ["B", "KB", "MB", "GB", "TB"]

    # Convert integer byte count into floating point so division produces
    # convenient decimal output.
    size = float(num_bytes)

    # Progressively divide by 1024 until the most appropriate unit is found.
    for unit in units:

        if size < 1024:
            return f"{size:.2f} {unit}"

        size /= 1024

    # Extremely large files beyond TB are reported as PB.
    return f"{size:.2f} PB"


# =============================================================================
# SHA-256 FUNCTION
# =============================================================================

def calculate_sha256(filename):
    """
    Calculate the SHA-256 hash of a file.

    IMPORTANT:

    The file is processed using STREAMING I/O.

    We DO NOT do this:

        data = open(filename, "rb").read()

    because that could attempt to load an entire multi-gigabyte MP4 into RAM.

    Instead:

        read 4 MB
            |
            v
        SHA-256 update
            |
            v
        read next 4 MB
            |
            v
        SHA-256 update
            |
           ...

    The resulting SHA-256 digest is identical regardless of chunk size.

    Returns:

        digest
            SHA-256 digest represented as hexadecimal text.

        elapsed_time
            Number of seconds required to hash the complete file.
    """

    print()
    print("      [SHA-256] Initializing SHA-256 context...")

    # Create a new SHA-256 hashing object.
    sha256 = hashlib.sha256()

    print(f"      [SHA-256] Opening input file: {filename}")
    print(
        f"      [SHA-256] Processing file in "
        f"{CHUNK_SIZE // (1024 * 1024)} MB chunks..."
    )

    # Record benchmark start time immediately before file processing.
    start_time = time.perf_counter()

    # Open input file in binary mode.
    #
    # Binary mode is essential because MP4 and other files must be processed
    # byte-for-byte without text encoding or newline translation.
    with open(filename, "rb") as f:

        chunk_number = 0
        bytes_processed = 0

        while True:

            # Read up to CHUNK_SIZE bytes from the input file.
            chunk = f.read(CHUNK_SIZE)

            # An empty byte string indicates EOF.
            if not chunk:
                break

            # Feed this block into the SHA-256 state.
            sha256.update(chunk)

            chunk_number += 1
            bytes_processed += len(chunk)

    # Calculate total elapsed hashing time.
    elapsed_time = time.perf_counter() - start_time

    print(
        f"      [SHA-256] Processed {chunk_number:,} chunks."
    )

    print(
        f"      [SHA-256] Processed {format_size(bytes_processed)}."
    )

    print(
        f"      [SHA-256] Hash calculation completed in "
        f"{elapsed_time:.6f} seconds."
    )

    # Convert the binary 32-byte SHA-256 digest into the familiar
    # 64-character hexadecimal representation.
    digest = sha256.hexdigest()

    return digest, elapsed_time


# =============================================================================
# AES-256-GCM ENCRYPTION FUNCTION
# =============================================================================

def encrypt_aes256_gcm(input_file, output_file, key):
    """
    Encrypt a file using AES-256-GCM.

    INPUT:

        input_file

            Original file to encrypt.

            Example:

                video.mp4


        output_file

            Destination encrypted file.

            Example:

                video.mp4.enc


        key

            Raw 32-byte AES key.


    OUTPUT FILE STRUCTURE:

        +-----------------------------+
        | MAGIC                       |
        | "AES256GCM01"               |
        +-----------------------------+
        | NONCE                       |
        | 12 bytes / 96 bits          |
        +-----------------------------+
        |                             |
        | AES-GCM CIPHERTEXT          |
        |                             |
        | Variable length             |
        |                             |
        +-----------------------------+
        | GCM AUTHENTICATION TAG      |
        | 16 bytes / 128 bits         |
        +-----------------------------+


    IMPORTANT:

    Although the file is READ in chunks, this implementation represents ONE
    AES-GCM cryptographic message.

    In other words, it does NOT create an independent GCM nonce/tag for every
    4 MB chunk.

    Instead:

        ONE key
        ONE nonce
        ONE GCM encryption context
        ONE final authentication tag

    are used for the complete file.

    Chunking here is primarily an I/O and memory-management technique.
    """

    print()
    print("      [AES-GCM] Generating fresh 96-bit GCM nonce...")

    # Generate 12 cryptographically random bytes.
    #
    # A fresh nonce is generated every time this function executes.
    nonce = os.urandom(NONCE_SIZE)

    print(
        f"      [AES-GCM] Nonce generated: {nonce.hex()}"
    )

    print("      [AES-GCM] Creating AES-256 cipher context...")

    # Construct AES + GCM.
    #
    # Because 'key' is exactly 32 bytes, algorithms.AES(key) selects AES-256.
    #
    # modes.GCM(nonce) configures Galois/Counter Mode using our fresh nonce.
    cipher = Cipher(
        algorithms.AES(key),
        modes.GCM(nonce)
    )

    # Create an encryption context.
    #
    # The context maintains the internal GCM state while successive chunks
    # are encrypted.
    encryptor = cipher.encryptor()

    print("      [AES-GCM] AES-256-GCM context initialized.")

    print(
        f"      [AES-GCM] Input  : {input_file}"
    )

    print(
        f"      [AES-GCM] Output : {output_file}"
    )

    print(
        f"      [AES-GCM] Chunk size: "
        f"{CHUNK_SIZE // (1024 * 1024)} MB"
    )

    # Start timing immediately before performing file I/O and encryption.
    #
    # Therefore the measured encryption time includes:
    #
    #       reading input file
    #       AES-GCM processing
    #       writing ciphertext
    #       writing header/tag
    #
    # This is an END-TO-END encryption throughput measurement rather than a
    # pure AES primitive benchmark.
    start_time = time.perf_counter()

    # Open:
    #
    #   input file  -> binary read
    #   output file -> binary write
    #
    with open(input_file, "rb") as infile, \
         open(output_file, "wb") as outfile:

        # ---------------------------------------------------------------------
        # WRITE MAGIC HEADER
        # ---------------------------------------------------------------------

        outfile.write(MAGIC)

        # ---------------------------------------------------------------------
        # WRITE GCM NONCE
        # ---------------------------------------------------------------------
        #
        # The nonce is not secret.
        #
        # It needs to be available during decryption, so storing it alongside
        # the ciphertext is normal.
        #
        outfile.write(nonce)

        chunk_number = 0
        bytes_processed = 0

        # ---------------------------------------------------------------------
        # STREAM FILE THROUGH AES-GCM
        # ---------------------------------------------------------------------

        while True:

            # Read next 4 MB block.
            chunk = infile.read(CHUNK_SIZE)

            # EOF reached.
            if not chunk:
                break

            # Encrypt this portion of plaintext.
            #
            # GCM state is maintained internally by 'encryptor'.
            encrypted_chunk = encryptor.update(chunk)

            # Immediately write encrypted bytes to disk.
            #
            # This prevents ciphertext from accumulating in RAM.
            outfile.write(encrypted_chunk)

            chunk_number += 1
            bytes_processed += len(chunk)

        print(
            f"      [AES-GCM] Processed {chunk_number:,} chunks."
        )

        print(
            f"      [AES-GCM] Processed {format_size(bytes_processed)}."
        )

        print("      [AES-GCM] Finalizing encryption context...")

        # Finalize the GCM operation.
        #
        # After this call, encryptor.tag becomes available.
        encryptor.finalize()

        # ---------------------------------------------------------------------
        # WRITE GCM AUTHENTICATION TAG
        # ---------------------------------------------------------------------
        #
        # This tag is required during decryption.
        #
        # A decryptor uses the tag to verify ciphertext integrity and
        # authenticity.
        #
        outfile.write(encryptor.tag)

    # End benchmark timing after the output file has been written.
    elapsed_time = time.perf_counter() - start_time

    print(
        f"      [AES-GCM] Authentication tag: "
        f"{encryptor.tag.hex()}"
    )

    print(
        f"      [AES-GCM] Encryption completed in "
        f"{elapsed_time:.6f} seconds."
    )

    return nonce, encryptor.tag, elapsed_time


# =============================================================================
# AES KEY LOADING FUNCTION
# =============================================================================

def load_key(key_file):
    """
    Load the raw AES-256 key.

    AES-256 requires:

        256 bits

    Since:

        8 bits = 1 byte

    therefore:

        256 / 8 = 32 bytes

    The supplied key file MUST therefore contain exactly 32 bytes.

    Examples of INVALID key files:

        "MyPassword123"

        64 ASCII hexadecimal characters

        Base64 text

    This program expects the ACTUAL binary key bytes.
    """

    print()
    print(f"[KEY] Loading AES key from: {key_file}")

    # Read complete key file.
    #
    # Since the expected file is only 32 bytes, there is no need for
    # streaming here.
    with open(key_file, "rb") as f:
        key = f.read()

    print(
        f"[KEY] Key file contains {len(key)} bytes."
    )

    # Validate key length.
    if len(key) != KEY_SIZE:

        print()
        print("=" * 70)
        print("ERROR: INVALID AES KEY")
        print("=" * 70)

        print()
        print("AES-256 requires exactly 32 raw key bytes.")
        print()
        print(f"Expected : {KEY_SIZE} bytes")
        print(f"Received : {len(key)} bytes")
        print()

        sys.exit(1)

    print("[KEY] AES-256 key length validated successfully.")
    print("[KEY] Key material will NOT be displayed.")

    return key


