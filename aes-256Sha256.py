#!/usr/bin/env python3

"""
===============================================================================
 AES-256-GCM FILE ENCRYPTION + SHA-256 BENCHMARK
 Android / Termux Test Utility
===============================================================================

PURPOSE
-------

This script is intended primarily for benchmarking cryptographic operations
on an Android device running Python through Termux.

The script performs TWO separate cryptographic operations against an input
file:

    1. SHA-256 hashing
    2. AES-256-GCM encryption

The operations are deliberately performed separately.

This is important for benchmarking because it allows us to measure:

    - Time required to calculate SHA-256
    - SHA-256 throughput in MB/s

    - Time required to perform AES-256-GCM encryption
    - AES-256-GCM throughput in MB/s

    - Combined cryptographic processing time
    - Overall script runtime

Typical test files may include large MP4 video files generated for testing
mobile video-processing performance.

For example:

    200 MB MP4
    1 GB MP4
    5 GB MP4
    10 GB MP4

The script uses STREAMING I/O.

This means the complete file is NOT loaded into RAM.

Instead, the file is processed in relatively small chunks (currently 4 MB).

This is particularly important on Android devices where:

    - RAM is shared with the Android operating system
    - Applications operate within memory constraints
    - Video files may be several GB in size
    - Loading an entire video into memory would be impractical

-------------------------------------------------------------------------------
CRYPTOGRAPHIC OPERATIONS
-------------------------------------------------------------------------------

SHA-256:

    Python hashlib.sha256()

AES encryption:

    AES-256-GCM

AES key size:

    256 bits
    32 bytes

GCM nonce:

    96 bits
    12 bytes

GCM authentication tag:

    128 bits
    16 bytes

-------------------------------------------------------------------------------
ENCRYPTED FILE FORMAT
-------------------------------------------------------------------------------

The generated encrypted file has the following simple test format:

    +----------------------+
    | MAGIC HEADER         |
    +----------------------+
    | 96-bit NONCE         |
    +----------------------+
    | ENCRYPTED DATA       |
    | ...                  |
    | ...                  |
    +----------------------+
    | 128-bit GCM TAG      |
    +----------------------+

In byte form:

    MAGIC || NONCE || CIPHERTEXT || TAG

The MAGIC value allows software to identify files generated by this
particular test utility.

-------------------------------------------------------------------------------
IMPORTANT SECURITY NOTE
-------------------------------------------------------------------------------

A fresh random GCM nonce is generated for EVERY encryption operation.

Nonce reuse with the same AES-GCM key can catastrophically compromise the
security of AES-GCM.

Therefore:

    NEVER deliberately reuse a nonce with the same AES key.

os.urandom() is used to obtain cryptographically secure random bytes from
the operating system.

-------------------------------------------------------------------------------
ANDROID / TERMUX
-------------------------------------------------------------------------------

Typical installation:

    pkg update
    pkg install python
    pip install cryptography

Allow Termux access to Android shared storage:

    termux-setup-storage

Typical Android shared-storage locations exposed by Termux:

    ~/storage/downloads/
    ~/storage/shared/
    ~/storage/dcim/

Example execution:

    python aes_gcm_benchmark.py \
        ~/storage/downloads/video.mp4 \
        ~/storage/downloads/aes.key \
        ~/storage/downloads/video.mp4.enc

-------------------------------------------------------------------------------
AES KEY
-------------------------------------------------------------------------------

The key file must contain EXACTLY 32 RAW BYTES.

This represents:

    32 bytes × 8 bits = 256 bits

The key file is NOT expected to contain:

    - hexadecimal text
    - Base64 text
    - a password
    - a passphrase

It contains the actual raw AES key bytes.

Example key generation using Python:

    python -c "import os; open('aes.key','wb').write(os.urandom(32))"

===============================================================================
"""


